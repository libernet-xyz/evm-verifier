import { expect } from "chai";
import hre, { network } from "hardhat";
import { type BaseContract, type Contract, dataLength } from "ethers";
import { decodePlonkProof, encodePlonkProof, loadPlonkCase } from "./vectors.js";

const { ethers } = await network.create();

const P = 0x7ffffffffffffffffffffffffffffffe0673ddf29e9b5547c000000000000001n;

/** The largest code size of a contract (EIP-170). */
const MAX_CODE_SIZE = 24576;

/** The largest gas limit of a transaction (EIP-7825). */
const MAX_TRANSACTION_GAS = 2n ** 24n;

/**
 * The Merkle lookup benchmarks (see `MerkleLookup.ts`), with the prefix of the names of the
 * libraries of their verifiers. The verifiers are generated by `make_solidity_verifier` of
 * `starkom-plonk` in `contracts/test/generated` (see `npm run verifiers:merkle`).
 */
const BENCHMARKS: { name: string; verifierName: string }[] = [
  { name: "binary-256-t4x7", verifierName: "Binary256T4X7" },
  { name: "binary-160-t4x7", verifierName: "Binary160T4X7" },
  { name: "ternary-162-t5x7", verifierName: "Ternary162T5X7" },
  { name: "ternary-101-t5x7", verifierName: "Ternary101T5X7" },
];

/** A generated verifier, deployed with its external gate libraries. */
interface Deployment {
  verifier: Contract;
  /** All the deployed libraries, the verifier last. */
  libraries: BaseContract[];
}

/**
 * Returns the names of the external gate libraries of a verifier, `<verifierName>Gates1`,
 * `<verifierName>Gates2`, etc., in order.
 */
async function gateLibraryNames(verifierName: string): Promise<string[]> {
  const prefix = `${verifierName}Gates`;
  const names = [...(await hre.artifacts.getAllFullyQualifiedNames())]
    .map((name) => name.split(":")[1])
    .filter((name) => name.startsWith(prefix) && /^\d+$/.test(name.slice(prefix.length)));
  return names.sort((a, b) => Number(a.slice(prefix.length)) - Number(b.slice(prefix.length)));
}

/** Deploys the external gate libraries of a verifier, then the verifier linked to them. */
async function deployVerifier(verifierName: string): Promise<Deployment> {
  const libraries: BaseContract[] = [];
  const links: Record<string, string> = {};
  for (const name of await gateLibraryNames(verifierName)) {
    const library = await ethers.deployContract(name);
    libraries.push(library);
    links[name] = await library.getAddress();
  }
  const verifier = await ethers.deployContract(`${verifierName}Verifier`, [], {
    libraries: links,
  });
  return { verifier, libraries: [...libraries, verifier] };
}

describe("Generated verifiers of the Merkle lookup benchmarks", function () {
  for (const { name, verifierName } of BENCHMARKS) {
    describe(name, function () {
      const lookup = loadPlonkCase(new URL("./vectors/merkle/", import.meta.url), name);
      let deployment: Deployment;

      before(async function () {
        deployment = await deployVerifier(verifierName);
      });

      // So that the proof has fewer queries than the circuit allows.
      it("has more grinding bits than the circuit requires", function () {
        const proof = decodePlonkProof(lookup.scpf, lookup.circuit);
        expect(proof.options.grindingBits).to.be.greaterThan(lookup.circuit.pcsConfig.grindingBits);
      });

      it("returns the public inputs of a valid proof", async function () {
        const { publicInputs } = decodePlonkProof(lookup.scpf, lookup.circuit);
        expect(await deployment.verifier.verify(lookup.scpf)).to.deep.equal(publicInputs);
      });

      it("rejects a tampered public input", async function () {
        const proof = decodePlonkProof(lookup.scpf, lookup.circuit);
        proof.publicInputs[0] = (proof.publicInputs[0] + 1n) % P;
        await expect(
          deployment.verifier.verify(encodePlonkProof(proof)),
        ).to.be.revertedWithCustomError(deployment.verifier, "ConstraintViolation");
      });

      it("fits every library in the code size limit of a contract", async function () {
        for (const library of deployment.libraries) {
          const code = await ethers.provider.getCode(await library.getAddress());
          expect(dataLength(code)).to.be.at.most(MAX_CODE_SIZE);
        }
      });

      it("fits in the gas limit of a transaction", async function () {
        const data = deployment.verifier.interface.encodeFunctionData("verify", [lookup.scpf]);
        const to = await deployment.verifier.getAddress();
        const gas = await ethers.provider.estimateGas({ to, data });
        console.log(`        total gas ${gas}`);
        expect(gas).to.be.at.most(MAX_TRANSACTION_GAS);
      });
    });
  }
});
