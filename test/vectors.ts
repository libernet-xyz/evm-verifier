import { type BytesLike, concat, toBeHex } from "ethers";
import { readFileSync } from "node:fs";

/**
 * A Merkle proof for a coset of FRI leaves (see `FriVerifier.verifyQuery`), decoded from a
 * `Query.LeafProof` protobuf.
 */
export interface FriLeafProof {
  coset: bigint[];
  path: string[];
}

/** A FRI query, decoded from a `Query` protobuf. */
export interface FriQuery {
  index: bigint;
  folds: FriLeafProof[];
}

/** The FRI parameters (see `FriOptions` in `FRI.sol`). */
export interface FriOptions {
  degreeBound: bigint;
  blowupLog2: bigint;
  foldRate: bigint;
  maxRounds: bigint;
}

/** A FRI commitment (see `FriCommitment` in `FRI.sol`). */
export interface FriCommitment {
  roots: string[];
  foldedPolynomial: bigint[];
}

/** A FRI test case generated by `starkom-pcs` with the Keccak-256 backend over BlueSky. */
export interface FriCase {
  name: string;
  options: FriOptions;
  commitment: FriCommitment;
  /** One query for every index of the extended domain. */
  queries: FriQuery[];
  /** The evaluation of the committed polynomial at every queried element. */
  values: bigint[];
}

/**
 * A `Query.LeafProof` protobuf in the canonical proto3 JSON mapping.
 *
 * `bytes` fields are base64 strings and fields with default values (e.g. empty arrays) are
 * omitted.
 */
interface RawLeafProof {
  cosetValues?: string[];
  merklePath?: string[];
}

/** A `Query` protobuf in the canonical proto3 JSON mapping (`uint64` fields are strings). */
interface RawQuery {
  index?: string;
  folds?: RawLeafProof[];
}

interface RawCase {
  name: string;
  degreeBound: number;
  blowupLog2: number;
  foldRate: number;
  /** A decimal string, because it can be `usize::MAX`. */
  maxRounds: string;
  roots: string[];
  foldedPolynomial: string[];
  queries: RawQuery[];
  values: string[];
}

/** Decodes a base64 scalar stored in little-endian byte order, as all scalars in the protobufs. */
function decodeScalar(base64: string): bigint {
  const bytes = Buffer.from(base64, "base64").reverse();
  return bytes.length > 0 ? BigInt("0x" + bytes.toString("hex")) : 0n;
}

/** Decodes a base64 hash into a 0x-prefixed hex string. */
function decodeHash(base64: string): string {
  const bytes = Buffer.from(base64, "base64");
  if (bytes.length !== 32) {
    throw new Error(`invalid hash length ${bytes.length}`);
  }
  return "0x" + bytes.toString("hex");
}

function convertLeafProof(proof: RawLeafProof): FriLeafProof {
  return {
    coset: (proof.cosetValues ?? []).map(decodeScalar),
    path: (proof.merklePath ?? []).map(decodeHash),
  };
}

/** Loads the FRI test vectors generated by `tools/fri-vectors`. */
export function loadFriCases(): FriCase[] {
  const raw: RawCase[] = JSON.parse(
    readFileSync(new URL("./vectors/fri.json", import.meta.url), "utf8")
  );
  return raw.map((testCase) => ({
    name: testCase.name,
    options: {
      degreeBound: BigInt(testCase.degreeBound),
      blowupLog2: BigInt(testCase.blowupLog2),
      foldRate: BigInt(testCase.foldRate),
      maxRounds: BigInt(testCase.maxRounds),
    },
    commitment: {
      roots: testCase.roots,
      foldedPolynomial: testCase.foldedPolynomial.map(BigInt),
    },
    queries: testCase.queries.map((query) => ({
      index: BigInt(query.index ?? "0"),
      folds: (query.folds ?? []).map(convertLeafProof),
    })),
    values: testCase.values.map(BigInt),
  }));
}

/** The DEEP-FRI parameters (see `DeepOptions` in `DEEP.sol`). */
export interface DeepOptions {
  degreeBound: bigint;
  blowupLog2: bigint;
  foldRate: bigint;
  maxRounds: bigint;
  grindingBits: bigint;
}

/** A batched DEEP-FRI commitment (see `DeepCommitment` in `DEEP.sol`). */
export interface DeepCommitment {
  batches: { root: string; numPolys: bigint }[];
}

/** An opened point (see `DeepPoint` in `DEEP.sol`). */
export interface DeepPoint {
  z: bigint;
  values: bigint[];
}

/** A Merkle proof for a leaf of a polynomial batch, decoded from a `MerkleProof` protobuf. */
export interface BatchLeafProof {
  leaf: bigint[];
  path: string[];
}

/**
 * A DEEP-FRI proof, decoded from a `Proof` protobuf. The verifier takes it encoded in the calldata
 * format (see `encodeDeepProof`).
 */
export interface DeepProof {
  options: DeepOptions;
  nonce: bigint;
  numPolys: bigint;
  points: DeepPoint[];
  friCommitment: FriCommitment;
  openings: { proofs: BatchLeafProof[] }[];
  queries: FriQuery[];
}

/** A DEEP-FRI test case generated by `starkom-pcs` with the Keccak-256 backend over BlueSky. */
export interface DeepCase {
  name: string;
  commitment: DeepCommitment;
  proof: DeepProof;
  /** The proof encoded in the calldata format by the `calldata` crate, as a hex string. */
  calldata: string;
}

/** A `Commitment` protobuf in the canonical proto3 JSON mapping. */
interface RawCommitment {
  batches?: { root: string; numPolys?: string }[];
}

/** A `Proof` protobuf in the canonical proto3 JSON mapping. */
interface RawProof {
  degreeBound?: string;
  blowupLog2?: number;
  foldRate?: number;
  maxRounds?: string;
  grindingBits?: number;
  nonce?: string;
  numPolys?: string;
  points?: { z?: string; v?: string[] }[];
  friRoots?: string[];
  foldedQuotient?: string[];
  openings?: { proofs?: { leafValues?: string[]; merklePath?: string[] }[] }[];
  queries?: RawQuery[];
}

/** Converts a `Commitment` protobuf in the canonical proto3 JSON mapping. */
export function convertDeepCommitment(raw: RawCommitment): DeepCommitment {
  return {
    batches: (raw.batches ?? []).map((batch) => ({
      root: decodeHash(batch.root),
      numPolys: BigInt(batch.numPolys ?? "0"),
    })),
  };
}

/** Converts a `Proof` protobuf in the canonical proto3 JSON mapping. */
export function convertDeepProof(raw: RawProof): DeepProof {
  return {
    options: {
      degreeBound: BigInt(raw.degreeBound ?? "0"),
      blowupLog2: BigInt(raw.blowupLog2 ?? 0),
      foldRate: BigInt(raw.foldRate ?? 0),
      maxRounds: BigInt(raw.maxRounds ?? "0"),
      grindingBits: BigInt(raw.grindingBits ?? 0),
    },
    nonce: BigInt(raw.nonce ?? "0"),
    numPolys: BigInt(raw.numPolys ?? "0"),
    points: (raw.points ?? []).map((point) => ({
      z: decodeScalar(point.z ?? ""),
      values: (point.v ?? []).map(decodeScalar),
    })),
    friCommitment: {
      roots: (raw.friRoots ?? []).map(decodeHash),
      foldedPolynomial: (raw.foldedQuotient ?? []).map(decodeScalar),
    },
    openings: (raw.openings ?? []).map((opening) => ({
      proofs: (opening.proofs ?? []).map((proof) => ({
        leaf: (proof.leafValues ?? []).map(decodeScalar),
        path: (proof.merklePath ?? []).map(decodeHash),
      })),
    })),
    queries: (raw.queries ?? []).map((query) => ({
      index: BigInt(query.index ?? "0"),
      folds: (query.folds ?? []).map(convertLeafProof),
    })),
  };
}

/** Loads the DEEP-FRI test vectors generated by `tools/deep-vectors`. */
export function loadDeepCases(): DeepCase[] {
  const raw: { name: string; commitment: RawCommitment; proof: RawProof; calldata: string }[] =
    JSON.parse(readFileSync(new URL("./vectors/deep.json", import.meta.url), "utf8"));
  return raw.map((testCase) => ({
    name: testCase.name,
    commitment: convertDeepCommitment(testCase.commitment),
    proof: convertDeepProof(testCase.proof),
    calldata: testCase.calldata,
  }));
}

/**
 * Encodes a non-negative integer of at most 64 bits as a varint of the calldata format (see
 * `ProofViewer` and the `calldata` crate): the number of leading one bits of the first byte is the
 * number of bytes that follow it, and the remaining bits hold the value in big-endian order.
 */
export function encodeVarint(value: bigint): string {
  if (value < 0n || value >= 1n << 64n) {
    throw new Error(`${value} doesn't fit in a varint`);
  }
  for (let length = 1n; length <= 8n; length++) {
    if (value >> (7n * length) === 0n) {
      const prefix = ((1n << (length - 1n)) - 1n) << (7n * length + 1n);
      return toBeHex(prefix | value, Number(length));
    }
  }
  return concat(["0xff", toBeHex(value, 8)]);
}

/**
 * An element of the heap of the calldata format: a small integer encoded as a varint, a field
 * element encoded inline as a 32-byte big-endian word, or a hash encoded as the varint index of its
 * word in the pool.
 */
type HeapItem = { varint: bigint } | { word: bigint } | { hash: string };

/**
 * Builds the pool of the hashes referenced by `items` and encodes the pool and the heap, like
 * `encode_items` in the `calldata` crate: the pool is sorted by decreasing number of references
 * and then by first reference.
 */
function encodeItems(items: HeapItem[]): string {
  const references = new Map<string, { count: number; first: number }>();
  items.forEach((item, position) => {
    if ("hash" in item) {
      const hash = item.hash.toLowerCase();
      const reference = references.get(hash);
      if (reference) {
        reference.count++;
      } else {
        references.set(hash, { count: 1, first: position });
      }
    }
  });
  const pool = [...references.keys()].sort((a, b) => {
    const [first, second] = [references.get(a)!, references.get(b)!];
    return second.count - first.count || first.first - second.first;
  });
  const indices = new Map(pool.map((hash, index) => [hash, BigInt(index)]));
  const parts: BytesLike[] = [encodeVarint(BigInt(pool.length)), ...pool];
  for (const item of items) {
    if ("varint" in item) {
      parts.push(encodeVarint(item.varint));
    } else if ("word" in item) {
      parts.push(toBeHex(item.word, 32));
    } else {
      parts.push(encodeVarint(indices.get(item.hash.toLowerCase())!));
    }
  }
  return concat(parts);
}

/** Lists the heap elements of the openings of FRI queries, one query after the other. */
function friItems(queries: FriQuery[]): HeapItem[] {
  return queries.flatMap((query) =>
    query.folds.flatMap((fold) => [
      ...fold.coset.map((word) => ({ word })),
      ...fold.path.map((hash) => ({ hash })),
    ])
  );
}

/**
 * Encodes a DEEP-FRI proof in the calldata format, like `encode_proof` in the `calldata` crate.
 *
 * Unlike the Rust encoder, this one also encodes malformed proofs as they are, so that tests can
 * check how the verifier rejects them: for example, openings and FRI queries are encoded in turn
 * even if there are more of one than of the other.
 */
export function encodeDeepProof(proof: DeepProof): string {
  const { options } = proof;
  const items: HeapItem[] = [
    options.degreeBound,
    options.blowupLog2,
    options.foldRate,
    options.maxRounds,
    options.grindingBits,
    proof.nonce,
    proof.numPolys,
    BigInt(proof.points.length),
  ].map((varint) => ({ varint }));
  for (const point of proof.points) {
    items.push({ word: point.z }, ...point.values.map((word) => ({ word })));
  }
  items.push(...proof.friCommitment.roots.map((hash) => ({ hash })));
  items.push({ varint: BigInt(proof.friCommitment.foldedPolynomial.length) });
  items.push(...proof.friCommitment.foldedPolynomial.map((word) => ({ word })));
  for (let i = 0; i < Math.max(proof.openings.length, proof.queries.length); i++) {
    for (const leafProof of proof.openings[i]?.proofs ?? []) {
      items.push(...leafProof.leaf.map((word) => ({ word })));
      items.push(...leafProof.path.map((hash) => ({ hash })));
    }
    if (i < proof.queries.length) {
      items.push(...friItems([proof.queries[i]]));
    }
  }
  return encodeItems(items);
}

/** Encodes the openings of FRI queries in the calldata format, one query after the other. */
export function encodeFriQueries(queries: FriQuery[]): string {
  return encodeItems(friItems(queries));
}

/** Encodes a Merkle path in the calldata format: the heap contains only the pool indices. */
export function encodeMerklePath(path: string[]): string {
  return encodeItems(path.map((hash) => ({ hash })));
}
