/**
 * A PLONK test case generated by `tools/plonk-vectors`: a proof encoded by `Proof::to_scpf` and its
 * circuit.
 */
export interface PlonkCase {
  name: string;
  circuit: PlonkCircuit;
  /** The SCPF data of the proof, as a hex string. */
  scpf: string;
}

/** A `<name>.circuit.json` file written by `tools/plonk-vectors`. */
interface RawCircuit {
  commitment: string;
  pcsConfig: Record<keyof DeepOptions, number>;
  numRows: number;
  numColumns: number;
  numGateSelectors: number;
  numQuotientChunks: number;
  blinded: boolean;
  rotations: number[];
  publicCells: { row: number; column: number }[];
}

/** Loads the test case `name` of `directory`: `<name>.scpf` and `<name>.circuit.json`. */
export function loadPlonkCase(directory: URL, name: string): PlonkCase {
  const raw: RawCircuit = JSON.parse(
    readFileSync(new URL(`${name}.circuit.json`, directory), "utf8"),
  );
  const config = raw.pcsConfig;
  return {
    name,
    circuit: {
      commitment: raw.commitment,
      pcsConfig: {
        degreeBound: BigInt(config.degreeBound),
        securityBits: BigInt(config.securityBits),
        blowupLog2: BigInt(config.blowupLog2),
        grindingBits: BigInt(config.grindingBits),
      },
      numRows: BigInt(raw.numRows),
      numColumns: BigInt(raw.numColumns),
      numGateSelectors: BigInt(raw.numGateSelectors),
      numQuotientChunks: BigInt(raw.numQuotientChunks),
      blinded: raw.blinded,
      rotations: raw.rotations.map(BigInt),
      publicCells: raw.publicCells.map(({ row, column }) => ({
        row: BigInt(row),
        column: BigInt(column),
      })),
    },
    scpf: hexlify(readFileSync(new URL(`${name}.scpf`, directory))),
  };
}

/** Loads all the test cases of `directory`, in alphabetical order. */
export function loadPlonkCases(directory: URL): PlonkCase[] {
  return readdirSync(directory)
    .filter((file) => file.endsWith(".scpf"))
    .sort()
    .map((file) => loadPlonkCase(directory, file.slice(0, -".scpf".length)));
}

/** The layout identifier of the SCPF data of PLONK proofs (see `PlonkVerifier`). */
export const PLONK_LAYOUT_IDENTIFIER = keccak256(toUtf8Bytes("starkom.proto.plonk.v12.Proof"));

/**
 * The layout identifier of the SCPF data passed to the harnesses other than PLONK proofs (see
 * `TestLayout.sol`).
 */
export const TEST_LAYOUT_IDENTIFIER = keccak256(toUtf8Bytes("test"));

/** The version of SCPF of the test vectors, i.e. of `starkom-scpf`: major, minor, and patch. */
export const VERSION: [number, number, number] = [1, 1, 0];

/**
 * Encodes the 64-byte header of SCPF data (see `ProofViewer`): the `SCPF` signature, the version
 * numbers at offsets 8 to 10, the layout identifier at offset 16, and the pool size at offset 48.
 * All the other bytes are 0.
 */
export function encodeHeader(
  layoutIdentifier: string,
  poolSize: number,
  version: [number, number, number] = VERSION,
): string {
  return concat([
    toUtf8Bytes("SCPF"),
    toBeHex(0, 4),
    new Uint8Array(version),
    toBeHex(0, 5),
    layoutIdentifier,
    toBeHex(poolSize, 4),
    toBeHex(0, 12),
  ]);
}

/**
 * Encodes a non-negative integer of at most 64 bits as an SCPF varint (see `ProofViewer`): the
 * number of leading one bits of the first byte is the number of bytes that follow it, and the
 * remaining bits hold the value in big-endian order.
 */
export function encodeVarint(value: bigint): string {
  if (value < 0n || value >= 1n << 64n) {
    throw new Error(`${value} doesn't fit in a varint`);
  }
  for (let length = 1n; length <= 8n; length++) {
    if (value >> (7n * length) === 0n) {
      const prefix = ((1n << (length - 1n)) - 1n) << (7n * length + 1n);
      return toBeHex(prefix | value, Number(length));
    }
  }
  return concat(["0xff", toBeHex(value, 8)]);
}

/**
 * An item of the stream of SCPF data: a small integer encoded as a varint, a field element encoded
 * as an inline 32-byte big-endian word, or a hash encoded as a pool reference, i.e. the varint
 * position of its word in the pool.
 */
type StreamItem = { varint: bigint } | { word: bigint } | { hash: string };

/**
 * Builds the pool of the hashes referenced by `items` and encodes the SCPF data, like
 * `scpf::Encoder` in `starkom-pcs`: the pool is sorted by decreasing number of references and then
 * by increasing value.
 */
function encodeItems(items: StreamItem[], layoutIdentifier: string): string {
  const counts = new Map<string, number>();
  for (const item of items) {
    if ("hash" in item) {
      const hash = item.hash.toLowerCase();
      counts.set(hash, (counts.get(hash) ?? 0) + 1);
    }
  }
  // The hashes are lowercase hex strings of the same length, so their order is the order of their
  // values.
  const pool = [...counts.keys()].sort(
    (a, b) => counts.get(b)! - counts.get(a)! || (a < b ? -1 : 1),
  );
  const indices = new Map(pool.map((hash, index) => [hash, BigInt(index)]));
  const parts: BytesLike[] = [encodeHeader(layoutIdentifier, pool.length), ...pool];
  for (const item of items) {
    if ("varint" in item) {
      parts.push(encodeVarint(item.varint));
    } else if ("word" in item) {
      parts.push(toBeHex(item.word, 32));
    } else {
      parts.push(encodeVarint(indices.get(item.hash.toLowerCase())!));
    }
  }
  return concat(parts);
}

/** Lists the stream items of the openings of FRI queries, one query after the other. */
function friItems(queries: FriQuery[]): StreamItem[] {
  return queries.flatMap((query) =>
    query.folds.flatMap((fold) => [
      ...fold.coset.map((word) => ({ word })),
      ...fold.path.map((hash) => ({ hash })),
    ]),
  );
}

/**
 * Encodes the openings of FRI queries in SCPF with `TEST_LAYOUT_IDENTIFIER`, one query after the
 * other.
 */
export function encodeFriQueries(queries: FriQuery[]): string {
  return encodeItems(friItems(queries), TEST_LAYOUT_IDENTIFIER);
}

/**
 * Encodes a Merkle path in SCPF with `TEST_LAYOUT_IDENTIFIER`: the stream contains only the pool
 * references.
 */
export function encodeMerklePath(path: string[]): string {
  return encodeItems(
    path.map((hash) => ({ hash })),
    TEST_LAYOUT_IDENTIFIER,
  );
}

/** A Merkle proof for a leaf of a polynomial batch: the values of the leaf and the path up. */
export interface BatchLeafProof {
  leaf: bigint[];
  path: string[];
}

/**
 * A PLONK proof, as encoded in SCPF by `Proof::to_scpf` (see `SCPF.md` in `starkom-plonk`).
 * Everything that the layout doesn't encode is derived from the circuit.
 */
export interface PlonkProofData {
  publicInputs: bigint[];
  /** The roots of the witness, permutation argument, and quotient batches. */
  roots: string[];
  options: ProofOptions;
  nonce: bigint;
  /** The evaluations of all the committed polynomials at every point, in increasing order of X. */
  evaluations: bigint[][];
  friCommitment: FriCommitment;
  /** The openings of the batches for every query. */
  openings: BatchLeafProof[][];
  /** The openings of the FRI rounds for every query. */
  folds: FriLeafProof[][];
}

/** Returns the numbers of polynomials of the batches of a commitment of `circuit`. */
export function batchSizes(circuit: PlonkCircuit): bigint[] {
  return [
    circuit.numGateSelectors + circuit.numColumns + 1n,
    circuit.numColumns,
    1n + circuit.numColumns,
    circuit.numQuotientChunks + (circuit.blinded ? 1n : 0n),
  ];
}

/** Returns the number of FRI queries, like `DeepVerifier.numQueries`. */
function numQueries(options: DeepOptions): bigint {
  const bits =
    options.grindingBits < options.securityBits ? options.securityBits - options.grindingBits : 0n;
  const queries = (bits + options.blowupLog2 - 1n) / options.blowupLog2;
  return queries > 0n ? queries : 1n;
}

/** Returns log2(n) for a power of 2 n. */
function log2(n: bigint): bigint {
  return BigInt(n.toString(2).length - 1);
}

/** Reads the stream of SCPF data (see `ProofViewer`). */
class Reader {
  private readonly bytes: Uint8Array;
  private readonly pool: string[] = [];
  private position: number;

  constructor(data: string, layoutIdentifier: string) {
    this.bytes = getBytes(data);
    if (hexlify(this.bytes.slice(16, 48)) !== layoutIdentifier) {
      throw new Error("unexpected layout identifier");
    }
    const poolSize = new DataView(this.bytes.buffer, this.bytes.byteOffset).getUint32(48);
    for (let i = 0; i < poolSize; i++) {
      this.pool.push(hexlify(this.bytes.slice(64 + 32 * i, 96 + 32 * i)));
    }
    this.position = 64 + 32 * poolSize;
  }

  /** Reads a varint (see `encodeVarint`). */
  varint(): bigint {
    const first = this.bytes[this.position++];
    let length = 0;
    while (length < 8 && (first << length) & 0x80) {
      length++;
    }
    let value = length < 8 ? BigInt(first & (0xff >> (length + 1))) : 0n;
    for (let i = 0; i < length; i++) {
      value = (value << 8n) | BigInt(this.bytes[this.position++]);
    }
    return value;
  }

  words(count: bigint): bigint[] {
    const words = [];
    for (let i = 0n; i < count; i++) {
      words.push(BigInt(hexlify(this.bytes.slice(this.position, this.position + 32))));
      this.position += 32;
    }
    return words;
  }

  hashes(count: bigint): string[] {
    const hashes = [];
    for (let i = 0n; i < count; i++) {
      hashes.push(this.pool[Number(this.varint())]);
    }
    return hashes;
  }

  finish(): void {
    if (this.position !== this.bytes.length) {
      throw new Error(`${this.bytes.length - this.position} bytes of trailing data`);
    }
  }
}

/**
 * Decodes the SCPF data of a PLONK proof of `circuit`, deriving the shape of the proof from the
 * circuit like `PlonkVerifier` does.
 */
export function decodePlonkProof(scpf: string, circuit: PlonkCircuit): PlonkProofData {
  const reader = new Reader(scpf, PLONK_LAYOUT_IDENTIFIER);
  const publicInputs = reader.words(BigInt(circuit.publicCells.length));
  const roots = reader.hashes(3n);
  const [degreeBound, securityBits, blowupLog2, foldRate, maxRounds, grindingBits] = [
    reader.varint(),
    reader.varint(),
    reader.varint(),
    reader.varint(),
    reader.varint(),
    reader.varint(),
  ];
  const options = { degreeBound, securityBits, blowupLog2, foldRate, maxRounds, grindingBits };
  const nonce = reader.varint();
  const sizes = batchSizes(circuit);
  const numPolys = sizes.reduce((sum, size) => sum + size, 0n);
  const evaluations = circuit.rotations.map(() => reader.words(numPolys));
  const rounds =
    log2(degreeBound) / foldRate < maxRounds ? log2(degreeBound) / foldRate : maxRounds;
  const friRoots = reader.hashes(rounds);
  const foldedPolynomial = reader.words(reader.varint());
  const height = log2(degreeBound) + blowupLog2;
  const openings: BatchLeafProof[][] = [];
  const folds: FriLeafProof[][] = [];
  for (let i = 0n; i < numQueries(options); i++) {
    openings.push(sizes.map((size) => ({ leaf: reader.words(size), path: reader.hashes(height) })));
    const queryFolds = [];
    for (let round = 0n; round < rounds; round++) {
      queryFolds.push({
        coset: reader.words(1n << foldRate),
        path: reader.hashes(height - (round + 1n) * foldRate),
      });
    }
    folds.push(queryFolds);
  }
  reader.finish();
  return {
    publicInputs,
    roots,
    options,
    nonce,
    evaluations,
    friCommitment: { roots: friRoots, foldedPolynomial },
    openings,
    folds,
  };
}

/**
 * Encodes a PLONK proof in SCPF, like `Proof::to_scpf` in `starkom-plonk`.
 *
 * Unlike the Rust encoder, this one also encodes malformed proofs as they are, so that tests can
 * check how the verifier rejects them: for example, the openings of the batches and of the FRI
 * rounds are encoded in turn even if there are more of one than of the other.
 */
export function encodePlonkProof(proof: PlonkProofData): string {
  const { options } = proof;
  const items: StreamItem[] = [
    ...proof.publicInputs.map((word) => ({ word })),
    ...proof.roots.map((hash) => ({ hash })),
    ...[
      options.degreeBound,
      options.securityBits,
      options.blowupLog2,
      options.foldRate,
      options.maxRounds,
      options.grindingBits,
      proof.nonce,
    ].map((varint) => ({ varint })),
  ];
  for (const values of proof.evaluations) {
    items.push(...values.map((word) => ({ word })));
  }
  items.push(...proof.friCommitment.roots.map((hash) => ({ hash })));
  items.push({ varint: BigInt(proof.friCommitment.foldedPolynomial.length) });
  items.push(...proof.friCommitment.foldedPolynomial.map((word) => ({ word })));
  for (let i = 0; i < Math.max(proof.openings.length, proof.folds.length); i++) {
    for (const leafProof of proof.openings[i] ?? []) {
      items.push(...leafProof.leaf.map((word) => ({ word })));
      items.push(...leafProof.path.map((hash) => ({ hash })));
    }
    for (const fold of proof.folds[i] ?? []) {
      items.push(...fold.coset.map((word) => ({ word })));
      items.push(...fold.path.map((hash) => ({ hash })));
    }
  }
  return encodeItems(items, PLONK_LAYOUT_IDENTIFIER);
}
