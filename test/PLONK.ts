import { expect } from "chai";
import { network } from "hardhat";
import { createHash } from "node:crypto";
import type { PlonkHarness } from "../types/ethers-contracts";
import {
  batchSizes,
  decodePlonkProof,
  encodePlonkProof,
  loadPlonkCase,
  loadPlonkCases,
  PLONK_LAYOUT_IDENTIFIER,
  type PlonkCase,
  type PlonkCircuit,
  type PlonkProofData,
  TEST_LAYOUT_IDENTIFIER,
} from "./vectors";

const { ethers } = await network.create();

const P = 0x7ffffffffffffffffffffffffffffffe0673ddf29e9b5547c000000000000001n;

const directory = new URL("./vectors/plonk/", import.meta.url);

// Proofs of Vitalik's circuit (x^3 + x + 5 = 35 with x = 3) generated by `tools/plonk-vectors`.
const cases = loadPlonkCases(directory);

function findCase(name: string): PlonkCase {
  return loadPlonkCase(directory, name);
}

const unblinded = findCase("unblinded");
const ground = findCase("grinding");
const blinded = findCase("blinded");

/** Returns `SHA3-256(text)` as a hex string. */
function sha3(text: string): string {
  return "0x" + createHash("sha3-256").update(text).digest("hex");
}

describe("PLONK verifier", function () {
  let harness: PlonkHarness;

  before(async function () {
    harness = await ethers.deployContract("PlonkHarness");
  });

  /** Returns a copy of the decoded proof of a test case, to be tampered with. */
  function decode(testCase: PlonkCase): PlonkProofData {
    return decodePlonkProof(testCase.scpf, testCase.circuit);
  }

  /** Encodes `proof` in SCPF and verifies it against `circuit`. */
  function verify(proof: PlonkProofData, circuit: PlonkCircuit = unblinded.circuit) {
    return harness.verify(circuit, encodePlonkProof(proof));
  }

  describe("constants", function () {
    it("has the layout identifier of `Proof::to_scpf`", async function () {
      expect(await harness.proofLayoutIdentifier()).to.equal(PLONK_LAYOUT_IDENTIFIER);
    });

    it("has the domain separators of the Rust implementation", async function () {
      expect(await harness.domainSeparators()).to.deep.equal([
        sha3("starkom/deep/transcript"),
        sha3("starkom/plonk/challenge/xi"),
      ]);
    });
  });

  describe("decodes and encodes proofs like the Rust implementation", function () {
    for (const testCase of cases) {
      it(testCase.name, function () {
        expect(encodePlonkProof(decode(testCase))).to.equal(testCase.scpf);
      });
    }
  });

  describe("accepts honest proofs", function () {
    for (const testCase of cases) {
      const { blinded, pcsConfig } = testCase.circuit;
      const { foldRate, maxRounds, grindingBits } = decode(testCase).options;
      const description =
        `${testCase.name} (${blinded ? "blinded" : "unblinded"}, ` +
        `blowup 2^${pcsConfig.blowupLog2}, fold rate ${foldRate}, ` +
        `max rounds ${maxRounds === 2n ** 32n - 1n ? "unlimited" : maxRounds}, ` +
        `${grindingBits} grinding bits)`;
      it(description, async function () {
        await harness.verify(testCase.circuit, testCase.scpf);
      });
    }

    it("returns the public inputs", async function () {
      const result = await harness.verify(unblinded.circuit, unblinded.scpf);
      expect(result.publicInputs).to.deep.equal([3n, 35n]);
    });

    it("returns the batches derived from the circuit", async function () {
      const result = await harness.verify(blinded.circuit, blinded.scpf);
      const roots = decode(blinded).roots;
      const sizes = batchSizes(blinded.circuit);
      expect(result.commitment.batches).to.deep.equal([
        [true, sizes[0], blinded.circuit.commitment],
        [true, sizes[1], roots[0]],
        [false, sizes[2], roots[1]],
        [false, sizes[3], roots[2]],
      ]);
    });

    it("returns the evaluations at every rotation", async function () {
      // The SCPF data holds the evaluations in increasing order of X-coordinate, the verifier
      // returns them in the order of the rotations, so the two are the same up to the order.
      const result = await harness.verify(unblinded.circuit, unblinded.scpf);
      const decoded = decode(unblinded).evaluations;
      expect(result.evaluations).to.have.length(unblinded.circuit.rotations.length);
      expect(result.evaluations.map((values) => values.join()).sort()).to.deep.equal(
        decoded.map((values) => values.join()).sort(),
      );
    });

    it("returns the parameters of the proof", async function () {
      const result = await harness.verify(ground.circuit, ground.scpf);
      const { options } = decode(ground);
      expect(result.options).to.deep.equal([
        options.degreeBound,
        options.securityBits,
        options.blowupLog2,
        options.foldRate,
        options.maxRounds,
        options.grindingBits,
      ]);
    });
  });

  // The checks of `CompressedCircuit::verify` that don't depend on the gates.
  describe("rejects proofs of another circuit", function () {
    function verifyWith(changes: Partial<PlonkCircuit>) {
      return harness.verify({ ...unblinded.circuit, ...changes }, unblinded.scpf);
    }

    it("rejects another circuit commitment", async function () {
      await expect(verifyWith({ commitment: "0x" + "42".repeat(32) })).to.revert(ethers);
    });

    it("rejects another number of gate selectors", async function () {
      const numGateSelectors = unblinded.circuit.numGateSelectors + 1n;
      await expect(verifyWith({ numGateSelectors })).to.revert(ethers);
    });

    it("rejects another number of columns", async function () {
      await expect(verifyWith({ numColumns: unblinded.circuit.numColumns + 1n })).to.revert(ethers);
    });

    it("rejects a number of columns that overflows", async function () {
      await expect(verifyWith({ numColumns: ethers.MaxUint256 })).to.be.revertedWithPanic(0x11);
    });

    it("rejects another number of quotient chunks", async function () {
      const numQuotientChunks = unblinded.circuit.numQuotientChunks - 1n;
      await expect(verifyWith({ numQuotientChunks })).to.revert(ethers);
    });

    it("rejects a blinded circuit", async function () {
      await expect(verifyWith({ blinded: true })).to.revert(ethers);
    });

    it("rejects other rotations", async function () {
      await expect(verifyWith({ rotations: [-1n, 0n, 1n] })).to.revert(ethers);
      await expect(verifyWith({ rotations: [0n, 2n] })).to.revert(ethers);
    });

    it("rejects another public cell", async function () {
      const publicCells = [...unblinded.circuit.publicCells, { row: 0n, column: 0n }];
      await expect(verifyWith({ publicCells })).to.revert(ethers);
    });

    it("rejects another security level", async function () {
      const pcsConfig = { ...unblinded.circuit.pcsConfig, securityBits: 129n };
      await expect(verifyWith({ pcsConfig })).to.be.revertedWithCustomError(
        harness,
        "OptionsMismatch",
      );
    });

    it("rejects fewer grinding bits than the circuit requires", async function () {
      const pcsConfig = { ...ground.circuit.pcsConfig, grindingBits: 9n };
      await expect(
        harness.verify({ ...ground.circuit, pcsConfig }, ground.scpf),
      ).to.be.revertedWithCustomError(harness, "OptionsMismatch");
    });
  });

  // Mirrors the rejection tests of `starkom_pcs::deep::tests`.
  describe("rejects invalid proofs like the Rust implementation", function () {
    it("accepts the untampered proof", async function () {
      await verify(decode(unblinded));
    });

    it("rejects a tampered evaluation", async function () {
      const proof = decode(unblinded);
      proof.evaluations[0][0] = (proof.evaluations[0][0] + 1n) % P;
      await expect(verify(proof)).to.revert(ethers);
    });

    it("rejects swapped evaluations", async function () {
      const proof = decode(unblinded);
      proof.evaluations.reverse();
      await expect(verify(proof)).to.revert(ethers);
    });

    it("rejects a tampered root", async function () {
      const proof = decode(unblinded);
      proof.roots[0] = "0x" + "42".repeat(32);
      await expect(verify(proof)).to.revert(ethers);
    });

    it("rejects another nonce", async function () {
      const proof = decode(ground);
      proof.nonce += 1n;
      await expect(verify(proof, ground.circuit)).to.revert(ethers);
    });

    it("rejects overstated grinding", async function () {
      const proof = decode(ground);
      proof.options.grindingBits = 127n;
      await expect(verify(proof, ground.circuit)).to.be.revertedWithCustomError(
        harness,
        "InsufficientProofOfWork",
      );
    });

    it("rejects understated grinding", async function () {
      const proof = decode(ground);
      proof.options.grindingBits = 0n;
      await expect(verify(proof, ground.circuit)).to.be.revertedWithCustomError(
        harness,
        "OptionsMismatch",
      );
    });

    it("rejects another security level", async function () {
      const proof = decode(unblinded);
      proof.options.securityBits = 126n;
      await expect(verify(proof)).to.be.revertedWithCustomError(harness, "OptionsMismatch");
    });

    it("rejects another degree bound", async function () {
      const proof = decode(unblinded);
      proof.options.degreeBound *= 2n;
      await expect(verify(proof)).to.be.revertedWithCustomError(harness, "OptionsMismatch");
    });

    it("rejects another fold rate", async function () {
      // The fold rate is bound into the transcript.
      const proof = decode(unblinded);
      proof.options.foldRate = 2n;
      await expect(verify(proof)).to.revert(ethers);
    });

    it("rejects another maximum number of rounds", async function () {
      const proof = decode(unblinded);
      proof.options.maxRounds = 1n;
      await expect(verify(proof)).to.revert(ethers);
    });

    it("rejects a missing query", async function () {
      const proof = decode(unblinded);
      proof.openings.pop();
      proof.folds.pop();
      await expect(verify(proof)).to.revert(ethers);
    });

    it("rejects missing openings", async function () {
      const proof = decode(unblinded);
      proof.openings.pop();
      await expect(verify(proof)).to.revert(ethers);
    });

    it("rejects a missing opening within a query", async function () {
      const proof = decode(unblinded);
      proof.openings[0].pop();
      await expect(verify(proof)).to.revert(ethers);
    });

    it("rejects swapped openings", async function () {
      const proof = decode(unblinded);
      [proof.openings[0], proof.openings[1]] = [proof.openings[1], proof.openings[0]];
      await expect(verify(proof)).to.be.revertedWithCustomError(harness, "RootHashMismatch");
    });

    it("rejects a tampered leaf value", async function () {
      const proof = decode(unblinded);
      const leaf = proof.openings[5][1].leaf;
      leaf[0] = (leaf[0] + 1n) % P;
      await expect(verify(proof)).to.be.revertedWithCustomError(harness, "RootHashMismatch");
    });

    it("rejects an opening from the wrong domain", async function () {
      const proof = decode(unblinded);
      proof.openings[0][0] = decode(findCase("blowup-8")).openings[0][0];
      await expect(verify(proof)).to.revert(ethers);
    });

    it("rejects an oversized opening path", async function () {
      // Same as `test_reject_oversized_opening_path` in the `starkom_pcs::deep` unit tests: with 64
      // more hashes, `1 << path.len()` would wrap around to the domain size.
      const proof = decode(unblinded);
      for (let i = 0; i < 64; i++) {
        proof.openings[0][0].path.push(ethers.ZeroHash);
      }
      await expect(verify(proof)).to.revert(ethers);
    });

    it("rejects a huge security level", async function () {
      const proof = decode(unblinded);
      // The largest value of a varint, which would mean 2^63 queries.
      proof.options.securityBits = 2n ** 64n - 1n;
      await expect(verify(proof)).to.revert(ethers);
    });

    it("rejects a FRI opening inconsistent with the DEEP quotient", async function () {
      // Every value of the first FRI coset is changed, so whatever its position the queried value
      // no longer matches the DEEP quotient computed from the openings.
      const proof = decode(unblinded);
      const coset = proof.folds[0][0].coset;
      for (let i = 0; i < coset.length; i++) {
        coset[i] = (coset[i] + 1n) % P;
      }
      await expect(verify(proof)).to.be.revertedWithCustomError(harness, "LeafValueMismatch");
    });

    it("rejects a tampered FRI root", async function () {
      const proof = decode(unblinded);
      proof.friCommitment.roots[0] = "0x" + "42".repeat(32);
      await expect(verify(proof)).to.revert(ethers);
    });

    it("rejects a tampered folded quotient without rounds", async function () {
      const testCase = findCase("blinded-without-rounds");
      const proof = decode(testCase);
      const coefficients = proof.friCommitment.foldedPolynomial;
      coefficients[1] = (coefficients[1] + 1n) % P;
      await expect(verify(proof, testCase.circuit)).to.revert(ethers);
    });

    // TODO: enable once the algebraic checks bind the public inputs to the proof.
    it("rejects a tampered public input");
  });

  // Checks performed by `Options::validate` and the `from_proto` methods.
  describe("rejects malformed proofs like `from_proto`", function () {
    it("rejects a zero degree bound", async function () {
      const proof = decode(unblinded);
      proof.options.degreeBound = 0n;
      await expect(verify(proof))
        .to.be.revertedWithCustomError(harness, "InvalidDegreeBound")
        .withArgs(0n);
    });

    it("rejects a zero fold rate", async function () {
      const proof = decode(unblinded);
      proof.options.foldRate = 0n;
      await expect(verify(proof)).to.be.revertedWithCustomError(harness, "InvalidFoldRate");
    });

    it("rejects a zero blowup factor", async function () {
      const proof = decode(unblinded);
      proof.options.blowupLog2 = 0n;
      await expect(verify(proof)).to.be.revertedWithCustomError(harness, "InvalidBlowupFactor");
    });

    it("rejects an oversized domain", async function () {
      const proof = decode(unblinded);
      proof.options.blowupLog2 = 64n;
      await expect(verify(proof))
        .to.be.revertedWithCustomError(harness, "DomainTooLarge")
        .withArgs(2n, 64n);
    });

    it("rejects a huge blowup factor without overflowing", async function () {
      const proof = decode(unblinded);
      // The largest value of a varint.
      proof.options.blowupLog2 = 2n ** 64n - 1n;
      await expect(verify(proof)).to.be.revertedWithCustomError(harness, "DomainTooLarge");
    });

    it("rejects too many rounds", async function () {
      const proof = decode(unblinded);
      proof.options.maxRounds = 2n ** 32n;
      await expect(verify(proof))
        .to.be.revertedWithCustomError(harness, "InvalidMaxRounds")
        .withArgs(2n ** 32n);
    });

    it("rejects unsatisfiable grinding", async function () {
      const proof = decode(ground);
      proof.options.grindingBits = 257n;
      await expect(verify(proof, ground.circuit))
        .to.be.revertedWithCustomError(harness, "InvalidGrindingBits")
        .withArgs(257n);
    });

    it("rejects the maximum number of grinding bits", async function () {
      const proof = decode(ground);
      // The largest value of a varint.
      proof.options.grindingBits = 2n ** 64n - 1n;
      await expect(verify(proof, ground.circuit))
        .to.be.revertedWithCustomError(harness, "InvalidGrindingBits")
        .withArgs(2n ** 64n - 1n);
    });

    it("rejects a non-canonical public input", async function () {
      const proof = decode(unblinded);
      proof.publicInputs[1] += P;
      await expect(verify(proof))
        .to.be.revertedWithCustomError(harness, "NonCanonicalScalar")
        .withArgs(proof.publicInputs[1]);
    });

    it("rejects a non-canonical evaluation", async function () {
      const proof = decode(unblinded);
      proof.evaluations[1][2] += P;
      await expect(verify(proof))
        .to.be.revertedWithCustomError(harness, "NonCanonicalScalar")
        .withArgs(proof.evaluations[1][2]);
    });

    it("rejects a non-canonical coefficient of the folded quotient", async function () {
      const proof = decode(unblinded);
      proof.friCommitment.foldedPolynomial[0] += P;
      await expect(verify(proof))
        .to.be.revertedWithCustomError(harness, "NonCanonicalScalar")
        .withArgs(proof.friCommitment.foldedPolynomial[0]);
    });

    it("rejects a non-canonical leaf value", async function () {
      const proof = decode(unblinded);
      proof.openings[3][1].leaf[0] += P;
      await expect(verify(proof))
        .to.be.revertedWithCustomError(harness, "NonCanonicalScalar")
        .withArgs(proof.openings[3][1].leaf[0]);
    });

    it("rejects a non-canonical FRI coset value", async function () {
      const proof = decode(unblinded);
      proof.folds[2][1].coset[0] += P;
      await expect(verify(proof))
        .to.be.revertedWithCustomError(harness, "NonCanonicalScalar")
        .withArgs(proof.folds[2][1].coset[0]);
    });
  });

  describe("rejects malformed SCPF data", function () {
    it("rejects trailing data", async function () {
      await expect(harness.verify(unblinded.circuit, ethers.concat([unblinded.scpf, "0x00"])))
        .to.be.revertedWithCustomError(harness, "TrailingData")
        .withArgs(1n);
    });

    it("rejects a truncated proof", async function () {
      const scpf = ethers.dataSlice(unblinded.scpf, 0, ethers.dataLength(unblinded.scpf) - 1);
      await expect(harness.verify(unblinded.circuit, scpf)).to.revert(ethers);
    });

    it("rejects another layout", async function () {
      const scpf = ethers.concat([
        ethers.dataSlice(unblinded.scpf, 0, 16),
        TEST_LAYOUT_IDENTIFIER,
        ethers.dataSlice(unblinded.scpf, 48),
      ]);
      await expect(harness.verify(unblinded.circuit, scpf))
        .to.be.revertedWithCustomError(harness, "LayoutMismatch")
        .withArgs(TEST_LAYOUT_IDENTIFIER);
    });

    it("rejects another major version", async function () {
      const scpf = ethers.concat([
        ethers.dataSlice(unblinded.scpf, 0, 8),
        "0x0b",
        ethers.dataSlice(unblinded.scpf, 9),
      ]);
      await expect(harness.verify(unblinded.circuit, scpf))
        .to.be.revertedWithCustomError(harness, "UnsupportedVersion")
        .withArgs(11n);
    });

    it("rejects an empty proof", async function () {
      await expect(harness.verify(unblinded.circuit, "0x")).to.be.revertedWithCustomError(
        harness,
        "TruncatedProof",
      );
    });
  });
});
